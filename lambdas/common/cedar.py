"""Cedar policies for AgentCore Policy (L5), generated from the rules and saved payees.

Shared by policy/gen_cedar.py (deploy time) and the approval workflow, which
re-syncs a household's allowlist when a new payee finishes its cooling period.

Cedar sees only the tool input, so:
  - the household is read from the sessionId prefix (L4 binds it to the real session);
  - the payee allowlist and category blocks are baked in from the payees table;
  - the daily total (R4) cannot be expressed here; L6 enforces it atomically.
"""

import json
import time
from pathlib import Path

import boto3

from common.money import paise_to_inr
from common.rules import limits_for

RULES_PATH = Path(__file__).with_name("rules.generated.json")
PAY = "payments___pay_saved_payee"
READ_TOOLS = (
    "payees___list_payees",
    "bills___lookup_bill",
    "approvals___request_approval",
    "rules___explain_rule",
    "family___alert_family",
)


def _dec(paise: int) -> str:
    return f'decimal("{paise // 100}.{paise % 100:02d}")'


def _set(values) -> str:
    return "[" + ", ".join(json.dumps(v) for v in sorted(values)) + "]"


def _head(effect: str, action: str, gateway_arn: str) -> str:
    return (
        f"{effect}(\n  principal is AgentCore::IamEntity,\n  action == AgentCore::Action::\"{action}\",\n"
        f'  resource == AgentCore::Gateway::"{gateway_arn}"\n)'
    )


def generate(rules_by_mode: dict, households: list[dict], payees: list[dict], gateway_arn: str, principals: list[str]) -> dict:
    """Return {policy_name: cedar_statement}."""
    who = f"{_set(principals)}.contains(principal.id)"
    out = {}

    read_actions = ", ".join(f'AgentCore::Action::"{a}"' for a in READ_TOOLS)
    out["kavach_read_tools"] = (
        f"// Non-payment tools: only the Kavach harness (and the C3 bench role) may call them.\n"
        f"permit(\n  principal is AgentCore::IamEntity,\n  action in [{read_actions}],\n"
        f'  resource == AgentCore::Gateway::"{gateway_arn}"\n)\nwhen {{ {who} }};'
    )

    for hh in sorted(households, key=lambda h: h["householdId"]):
        hid, lim = hh["householdId"], limits_for(rules_by_mode[hh["mode"]])
        key = hid.replace("-", "_")
        session = f'context.input.sessionId like "kv-{hid}-*"'
        active = [p for p in payees if p["householdId"] == hid and p.get("status") == "active"]
        blocked = [p["payeeId"] for p in active if p["category"] in lim.blocked_categories]
        held_cats = lim.category_hold.categories if lim.category_hold else frozenset()
        normal = [p["payeeId"] for p in active if p["category"] not in lim.blocked_categories | held_cats]
        held = [p["payeeId"] for p in active if p["category"] in held_cats]

        out[f"{key}_pay"] = (
            f"// {hid} ({lim.mode}): R1 saved payees only, R3 per-payment limit {paise_to_inr(lim.per_payment_paise)}.\n"
            f"{_head('permit', PAY, gateway_arn)}\nwhen {{\n  {who} &&\n  {session} &&\n"
            f"  {_set(normal)}.contains(context.input.payeeId) &&\n"
            f'  context.input.amountInr.greaterThan(decimal("0.00")) &&\n'
            f"  context.input.amountInr.lessThanOrEqual({_dec(lim.per_payment_paise)})\n}};"
        )
        if held:
            th = min(lim.category_hold.threshold_paise, lim.per_payment_paise)
            out[f"{key}_pay_held_category"] = (
                f"// {hid}: S1 {sorted(held_cats)} payees only up to {paise_to_inr(th)} without the wait.\n"
                f"{_head('permit', PAY, gateway_arn)}\nwhen {{\n  {who} &&\n  {session} &&\n"
                f"  {_set(held)}.contains(context.input.payeeId) &&\n"
                f'  context.input.amountInr.greaterThan(decimal("0.00")) &&\n'
                f"  context.input.amountInr.lessThanOrEqual({_dec(th)})\n}};"
            )
        # Forbids win over any permit, so a later permit mistake can't reopen these.
        out[f"{key}_forbid_over_limit"] = (
            f"// {hid}: R3, nothing above {paise_to_inr(lim.per_payment_paise)} in one payment.\n"
            f"{_head('forbid', PAY, gateway_arn)}\nwhen {{\n  {session} &&\n"
            f"  context.input.amountInr.greaterThan({_dec(lim.per_payment_paise)})\n}};"
        )
        if blocked:
            out[f"{key}_forbid_blocked_category"] = (
                f"// {hid}: R8, no payments to {sorted(lim.blocked_categories)} payees, even saved ones.\n"
                f"{_head('forbid', PAY, gateway_arn)}\nwhen {{\n  {session} &&\n"
                f"  {_set(blocked)}.contains(context.input.payeeId)\n}};"
            )
    return out


def render(policies: dict) -> str:
    header = "// GENERATED by policy/gen_cedar.py from rules/*.yaml and the payees table. Do not edit.\n"
    return header + "\n\n".join(f"// @name {name}\n{stmt}" for name, stmt in policies.items()) + "\n"


def apply(policies: dict, engine_id: str, ctl=None, prune: bool = True, wait: bool = True) -> None:
    """Create or update each named policy; with prune, delete ones no longer generated."""
    ctl = ctl or boto3.client("bedrock-agentcore-control")
    existing = {}
    for page in ctl.get_paginator("list_policies").paginate(policyEngineId=engine_id):
        existing.update({p["name"]: p for p in page["policies"]})

    for name, stmt in policies.items():
        args = {"definition": {"cedar": {"statement": stmt}}, "validationMode": "FAIL_ON_ANY_FINDINGS"}
        if name in existing:
            ctl.update_policy(policyEngineId=engine_id, policyId=existing[name]["policyId"], **args)
            print(f"updated {name}")
        else:
            ctl.create_policy(policyEngineId=engine_id, name=name, **args)
            print(f"created {name}")
    for name, p in existing.items():
        if prune and name not in policies:
            ctl.delete_policy(policyEngineId=engine_id, policyId=p["policyId"])
            print(f"deleted stale {name}")

    if not wait:
        return
    deadline = time.time() + 180
    while time.time() < deadline:
        states = {}
        for page in ctl.get_paginator("list_policies").paginate(policyEngineId=engine_id):
            states.update({p["name"]: (p["status"], p.get("statusReasons")) for p in page["policies"]})
        pending = {n: s for n, s in states.items() if n in policies and s[0] != "ACTIVE"}
        failed = {n: s for n, s in pending.items() if s[0].endswith("FAILED")}
        if failed:
            raise RuntimeError(f"policy creation failed: {json.dumps(failed, indent=2, default=str)}")
        if not pending:
            print(f"{len(policies)} policies ACTIVE")
            return
        time.sleep(3)
    raise RuntimeError(f"timed out waiting for policies: {pending}")
